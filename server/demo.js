// Demo-mode stand-ins for Muse responses. Used only when META_API_KEY is missing
// (or DEMO_MODE=1). Every string here is prefixed so it can never be mistaken
// for real model output on screen or in a recording.

const DEMO_PREFIX = '[DEMO MODE — no Muse API key set]';

const HANDWRITTEN = {
  s3: {
    summary:
      'Five ways a CPU picks the next process. Each one fixes a problem of the one before it.',
    points: [
      '**FCFS** runs processes in arrival order. Simple, but short jobs get stuck behind one long job (the **convoy effect**).',
      '**SJF** runs the shortest next burst first. It gives the **lowest average waiting time**, but needs a burst-length guess. Its preemptive form is **SRTF** (Shortest-Remaining-Time-First).',
      '**Priority** always runs the highest-priority process. Low-priority jobs can **starve**; **aging** fixes this by slowly raising their priority.',
      '**Round Robin** gives each process a fixed **time quantum** (10–100 ms), then sends it to the back of the queue. A huge quantum turns RR into **FCFS**; a tiny one wastes time on context switches.',
      '**MLFQ** uses several queues. Use your whole quantum and you are **demoted**; wait too long and you are **promoted**. Favors short interactive jobs, but is the hardest to configure.'
    ],
    image_prompt:
      'A clean flat infographic comparing five CPU scheduling algorithms (FCFS, SJF/SRTF, Priority with aging, Round Robin with time quantum, Multilevel Feedback Queue) as five labeled cards with simple icons and one-line takeaways, white background, exam study sheet style'
  }
};

function sentences(text) {
  return text.match(/[^.!?]+[.!?]+/g)?.map((s) => s.trim()) ?? [text];
}

function demoText(segment, style) {
  const hand = HANDWRITTEN[segment.id];
  const base = hand ?? {
    summary: sentences(segment.text)[0],
    points: sentences(segment.text).slice(1, 5),
    image_prompt: `A simple flat diagram summarizing: ${segment.heading}`
  };
  return {
    summary: `${DEMO_PREFIX} ${base.summary}`,
    points: base.points,
    image_prompt: base.image_prompt
  };
}

function esc(s) {
  return String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
}

// A plain SVG placeholder standing in for a Muse Image result.
function demoImage(segment) {
  const cards =
    segment.id === 's3'
      ? [
          ['FCFS', 'arrival order', 'convoy effect'],
          ['SJF / SRTF', 'shortest burst first', 'lowest avg wait'],
          ['Priority', 'highest first', 'aging stops starvation'],
          ['Round Robin', 'fixed quantum', 'big quantum = FCFS'],
          ['MLFQ', 'many queues', 'demote / promote']
        ]
      : [[segment.heading, '', '']];
  const w = 600;
  const rowH = 74;
  const h = 70 + cards.length * rowH + 30;
  const rows = cards
    .map(
      ([t, a, b], i) => `
    <g transform="translate(20 ${60 + i * rowH})">
      <rect width="${w - 40}" height="${rowH - 12}" rx="12" fill="#eef2ff" stroke="#6366f1"/>
      <text x="16" y="27" font-size="20" font-weight="700" fill="#312e81">${esc(t)}</text>
      <text x="16" y="50" font-size="15" fill="#3730a3">${esc(a)}${b ? ' · ' + esc(b) : ''}</text>
    </g>`
    )
    .join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" font-family="system-ui,sans-serif">
  <rect width="100%" height="100%" fill="#ffffff"/>
  <text x="20" y="34" font-size="16" font-weight="700" fill="#b45309">${esc(DEMO_PREFIX)}</text>
  ${rows}
  <text x="20" y="${h - 12}" font-size="13" fill="#6b7280">Placeholder diagram — not generated by Muse Image</text>
</svg>`;
  return 'data:image/svg+xml;base64,' + Buffer.from(svg).toString('base64');
}

module.exports = { DEMO_PREFIX, demoText, demoImage };
